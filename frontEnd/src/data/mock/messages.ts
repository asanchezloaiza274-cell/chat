const min = (n: number) => new Date(Date.now() - n * 60 * 1000).toISOString();
const hr = (n: number) => new Date(Date.now() - n * 3600 * 1000).toISOString();
function dayAt(daysBack: number, hour: number, minute: number): string {
  const d = new Date();
  d.setDate(d.getDate() - daysBack);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
}

